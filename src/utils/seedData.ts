import { ParsedFtpItem } from './ftpParser';

export function createSeedItem(item: {
  id: string;
  rawName: string;
  cleanTitle: string;
  url: string;
  mediaKind: 'movie' | 'series';
  year?: number;
  quality?: string;
  audioTag?: string;
  imdbRating?: string;
  episode?: number;
  posterUrl?: string;
  backdropUrl?: string;
  plot?: string;
  genres?: string[];
  runtime?: string;
  sourceServerName?: string;
  sourceServerUrl?: string;
}): ParsedFtpItem {
  return {
    id: item.id,
    rawName: item.rawName,
    cleanTitle: item.cleanTitle,
    url: item.url,
    isDirectory: item.mediaKind === 'series' && item.episode === undefined,
    mediaKind: item.mediaKind,
    year: item.year,
    quality: item.quality,
    audioTag: item.audioTag,
    imdbRating: item.imdbRating,
    episode: item.episode,
    posterUrl: item.posterUrl,
    backdropUrl: item.backdropUrl,
    plot: item.plot,
    genres: item.genres,
    runtime: item.runtime,
    sourceServerName: item.sourceServerName,
    sourceServerUrl: item.sourceServerUrl,
    sizeFormatted: item.mediaKind === 'series' ? '' : '2.8 GB',
    lastModified: '2026-06-05',
  };
}

